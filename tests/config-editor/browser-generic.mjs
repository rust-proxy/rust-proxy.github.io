import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { checkLayout } from './layout.mjs';

const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE_PATH ?? 'playwright');
const base = process.env.PREVIEW_URL;
assert.ok(base, 'Use run-browser.py to provide a bounded local server');
const channel = process.env.BROWSER_CHANNEL ?? (process.env.CI ? 'chromium' : 'msedge');
const browser = await chromium.launch({ channel, headless: true });
const page = await browser.newPage();
const errors = [];
const external = [];
page.on('pageerror', e => errors.push(e.message));
await page.route('**/*', route => {
  if (route.request().url().startsWith(new URL(base).origin)) return route.continue();
  external.push(route.request().url());
  return route.abort();
});
const field = key => page.locator(`[id="field-${key}"]`);
const chrome = key => page.locator(`#${key}`);
const lines = () => page.locator('.preview-doc__line');
const click = name => page.getByRole('button', { name, exact: true }).click();
const output = async () => JSON.parse((await page.locator('.preview-doc__line code').allTextContents()).join('\n'));
try {
  await page.goto(`${base}?schema=example`);
  await page.waitForSelector('#editor[data-ready="true"]');
  assert.equal(await page.title(), 'Notebook 任务清单编辑器');
  assert.equal(await chrome('editor-schema').inputValue(), 'example');
  assert.equal(await field('project').count(), 1, 'selection region shows the generic form');
  assert.ok((await lines().allTextContents()).some(line => line.includes('"title"')), 'preview region shows the generated snapshot');
  const secretLine = lines().filter({ hasText: '"secret"' }).first();
  assert.match(await secretLine.getAttribute('aria-label'), /敏感/, 'generic preview lines carry XML descriptions');
  await field('encoding').selectOption('toml');
  assert.ok((await lines().allTextContents()).some(line => line.includes('[[items]]')));
  assert.ok(await page.locator('.preview-doc__line code .token.class-name').count() > 0, 'TOML tables are highlighted');
  await field('encoding').selectOption('yaml');
  assert.ok((await lines().allTextContents()).some(line => line.includes('title: "example"')));
  assert.ok(await page.locator('.preview-doc__line code .token.atrule').count() > 0, 'YAML keys are highlighted');
  await field('encoding').selectOption('json');

  assert.equal(await field('seed').inputValue().then(v => v.length), 16);
  const seed = await field('seed').inputValue();
  await field('confirm').check();
  await click('生成随机值');
  assert.notEqual(await field('seed').inputValue(), seed);
  assert.equal(await field('confirm').isChecked(), false, 'Generated field changes apply XML resets too');
  assert.equal((await output()).items[0].enabled, true);
  await field('entries.0.enabled').uncheck();
  assert.equal((await output()).items[0].enabled, false, 'Collection boolean fields must use real checkboxes');
  await field('entries.0.id').fill('kept');
  const token = await field('entries.0.token').inputValue();
  await click('更新标记');
  assert.equal(await field('entries.0.id').inputValue(), 'kept');
  assert.equal(await field('entries.0.enabled').isChecked(), false);
  assert.notEqual(await field('entries.0.token').inputValue(), token);
  assert.equal((await output()).items[0].secret, '••••••••');
  await chrome('editor-reveal').check();
  assert.equal((await output()).items[0].secret.length, 24);
  await click('添加项目');
  await field('entries.1.id').fill('second');
  const retainedRow = await field('entries.1.id').elementHandle();
  await field('chosen').selectOption('1');
  await click('单项清单');
  assert.equal((await output()).item, 'second');
  await click('移除项目 1');
  assert.equal((await output()).item, 'second');
  assert.equal(await retainedRow.evaluate(node => node.isConnected && node.id === 'field-entries.0.id'), true,
    'Removing an earlier row retains the same DOM input and updates its error/label path');
  await field('entries.0.id').focus();
  await field('entries.0.id').pressSequentially('-edited');
  assert.equal(await retainedRow.evaluate(node => document.activeElement === node), true);
  await field('entries.0.id').fill('second');
  await click('单个项目');
  assert.equal(await page.getByRole('button', { name: '完整清单', exact: true }).isVisible(), false);
  await field('confirm').check();
  await click('审计信息');
  assert.equal((await output()).confirmed, true);
  await field('project').fill('changed');
  assert.equal(await field('confirm').isChecked(), false);
  assert.equal((await output()).item, 'second', 'Hidden output selection falls back to a visible output');
  await click('全部清单');
  await click('完整清单');
  await field('encoding').selectOption('toml');
  assert.equal(await page.locator('.preview__command').textContent(), 'notebook --input snapshot.toml');
  await field('first').fill('50');
  assert.equal(await page.getByRole('button', { name: '下载配置', exact: true }).isDisabled(), true);
  const validationTarget = await page.locator('[aria-invalid="true"]').first().getAttribute('id');
  await page.locator('.preview__errors button').first().click();
  assert.equal(await page.evaluate(() => document.activeElement?.id), validationTarget, 'Validation links move focus to the invalid field');
  await field('last').fill('60');
  assert.equal(await page.getByRole('button', { name: '下载配置', exact: true }).isEnabled(), true);
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await checkLayout(page, { field: 'first', secret: 'entries.0.token', name: 'generic' });
  assert.deepEqual(external, []);
  assert.deepEqual(errors, []);
  console.log('PASS: alternate XML branding, merged preview descriptions, arbitrary fields/collections, generated values, resets, validation and three outputs');

  const failurePage = await browser.newPage();
  failurePage.on('pageerror', e => errors.push(e.message));
  await failurePage.route('**/*', route => route.request().url().startsWith(new URL(base).origin) ? route.continue() : route.abort());
  await failurePage.addInitScript(() => {
    let calls = 0;
    Object.defineProperty(Crypto.prototype, 'getRandomValues', { value(bytes) {
      if (++calls > 1) throw new DOMException('Random unavailable');
      return bytes.fill(0xab);
    } });
  });
  await failurePage.goto(base);
  await failurePage.waitForSelector('#editor[data-ready="true"]');
  assert.equal(await failurePage.locator('#field-seed').inputValue(), '', 'Failed initialization must not apply partial random values');
  assert.match(await failurePage.locator('.status-bar').textContent(), /无法安全生成随机值/);
  await failurePage.getByRole('button', { name: '添加项目', exact: true }).click();
  assert.equal(await failurePage.locator('.collection-row').count(), 1, 'Failed randomness must not add a partial row');
  await failurePage.locator('#field-project').fill('manual');
  assert.equal(await failurePage.locator('#field-project').inputValue(), 'manual', 'Manual editing still works');
  assert.deepEqual(errors, []);
  await failurePage.close();
  console.log('PASS: failed Crypto API calls preserve state and allow manual editing');
} finally {
  await browser.close();
}
